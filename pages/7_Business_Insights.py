import os
import sys
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from dotenv import load_dotenv
load_dotenv()

import streamlit as st
import pandas as pd

from src.ui_utils import (
    configure_page, render_page_header, get_spark,
    insight_card, section_header,
    pipeline_not_run_error, check_processed_data,
    data_source_badge,
)
from src.data_loader import load_parquet
from src.insights import generate_insights

configure_page("Business Insights", "💡")

if not check_processed_data():
    pipeline_not_run_error()
    st.stop()

render_page_header(
    title="Business Insights Engine",
    subtitle="Automated strategic intelligence · Empirical findings derived directly from PySpark aggregations across 100k Brazilian orders",
    icon="💡",
    badge_text="Algorithmic Synthesis",
)

spark = get_spark()

with st.spinner("Executing analytical queries across Parquet tables…"):
    om_df = load_parquet(spark, "order_metrics")
    rfm_df = load_parquet(spark, "customer_rfm")
    item_df = load_parquet(spark, "item_data")
    pay_df = load_parquet(spark, "payments_clean")
    insights = generate_insights(om_df, rfm_df, item_df, pay_df)

if not insights:
    st.info("ℹ️ Insufficient analytical records available to generate insights.")
    st.stop()

# ── Categorized insights ─────────────────────────────────────────────────────
categories = ["Revenue", "Products", "Geography", "Customers", "Operations", "Payments", "Trends"]

for cat in categories:
    cat_insights = [i for i in insights if i.get("category") == cat]
    if not cat_insights:
        continue

    icon_map = {
        "Revenue": "💰", "Products": "🏷️", "Geography": "🗺️",
        "Customers": "👥", "Operations": "⚡", "Payments": "💳", "Trends": "📈",
    }
    section_header(f"{cat} Intelligence", icon=icon_map.get(cat, "🔹"))

    cols = st.columns(min(len(cat_insights), 2))
    for idx, insight in enumerate(cat_insights):
        with cols[idx % len(cols)]:
            insight_card(insight)

st.markdown("---")

# ── Data Pipeline Audit Summary ──────────────────────────────────────────────
section_header("Big Data Engineering & Pipeline Audit", icon="📋")

with st.expander("🔍 View Processed Record Counts & Audit Details", expanded=True):
    total_orders = om_df.count()
    total_items = item_df.count()
    total_customers = rfm_df.count()
    total_payments = pay_df.count()

    st.markdown(
        f"""
| Processed Table | Row Count | Ingestion Source | Grain / Primary Entity |
|---|---|---|---|
| **`order_metrics`** | **{total_orders:,}** | `olist_orders_dataset.csv` + Items + Reviews | Distinct Order (`order_id`) |
| **`customer_rfm`** | **{total_customers:,}** | Filtered Non-Canceled `order_metrics` | Unique Customer (`customer_unique_id`) |
| **`item_data`** | **{total_items:,}** | `olist_order_items_dataset.csv` + Translations | Individual Merchandise Line (`order_item_id`) |
| **`payments_clean`** | **{total_payments:,}** | `olist_order_payments_dataset.csv` | Financial Transaction Sequence |

**Key Data Engineering Guardrails:**
- **Join Inflation Prevention:** One-to-many items, payment records, and reviews are pre-aggregated before joining at the order grain, preventing artificial revenue inflation.
- **Customer Identity Resolution:** RFM segmentation operates on `customer_unique_id` rather than order-scoped `customer_id`.
- **Merchandise Revenue Precision:** Product revenue strictly represents `Σ(item price)` excluding freight, preserving core mercantile margin visibility.
        """
    )

st.markdown("---")

# Metric definitions
section_header("Analytical Metric Governance", icon="📐")
with st.expander("📖 View Formal Metric Definitions & Formulas", expanded=False):
    st.markdown("""
| Metric Name | Formal Definition | Methodological Scope |
|---|---|---|
| **Product Revenue** | `Σ(item_price)` | Excludes shipping freight costs |
| **Average Order Value (AOV)** | `Product Revenue ÷ Distinct Orders` | Evaluated across eligible filtered orders |
| **Repeat Customer** | Any `customer_unique_id` having `> 1` distinct `order_id` | Cohort-wide repeat detection |
| **Repeat Purchase Rate** | `(Repeat Customers ÷ Total Unique Customers) × 100` | Percentage of multi-order buyers |
| **Recency (R)** | Days elapsed from customer's latest order to reference date (`max(date) + 1`) | 1–5 quintile scale (5 = most recent) |
| **Frequency (F)** | Total count of distinct orders placed by `customer_unique_id` | 1–5 scale with deterministic tie-breaker |
| **Monetary (M)** | Total lifetime merchandise revenue generated by customer | 1–5 quintile scale (5 = top spenders) |
| **Delivery Delay** | `Actual Delivery Timestamp − Estimated Delivery Timestamp` | Positive = Late arrival; Negative = Early |
| **Late Delivery Incident** | Any completed delivery where `delivery_delay_days > 0` | Fulfillment SLA performance metric |
    """)

data_source_badge()
